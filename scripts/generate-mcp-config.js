#!/usr/bin/env node
"use strict";

const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");

function main(argv = process.argv.slice(2)) {
  const options = parseArgs(argv);
  const repoPath = path.resolve(options.repoPath || ROOT);
  const outDir = path.resolve(options.outDir || path.join(ROOT, ".runtime", "generated-configs"));
  const mode = options.mode || "source";
  if (!["source", "package"].includes(mode)) {
    throw new Error(`Unsupported mode: ${mode}. Expected source or package.`);
  }

  const config = buildMcpConfig(repoPath, mode);
  fs.mkdirSync(outDir, { recursive: true });

  const codexPath = path.join(outDir, "codex-mcp.toml");
  const claudePath = path.join(outDir, "mcp-launch.json");
  const readmePath = path.join(outDir, "README.md");

  fs.writeFileSync(codexPath, renderCodexToml(config), "utf8");
  fs.writeFileSync(claudePath, `${JSON.stringify(renderClaudeJson(config), null, 2)}\n`, "utf8");
  fs.writeFileSync(readmePath, renderReadme(config), "utf8");

  const summary = {
    ok: true,
    mode,
    outDir,
    files: {
      codex: codexPath,
      claude: claudePath,
      notes: readmePath
    },
    safeToCommit: false,
    note: "Generated files may contain local absolute paths; keep them under .runtime or another private local directory."
  };

  console.log(JSON.stringify(summary, null, 2));
}

function buildMcpConfig(repoPath, mode) {
  if (mode === "package") {
    return {
      serverName: "overleaf_browser_bridge",
      command: "npx",
      args: ["overleaf-browser-bridge"],
      env: {}
    };
  }
  return {
    serverName: "overleaf_browser_bridge",
    command: "node",
    args: [path.join(repoPath, "server", "overleaf-bridge-mcp.js")],
    env: {}
  };
}

function renderCodexToml(config) {
  const lines = [
    "# Generated by scripts/generate-mcp-config.js.",
    "# Review before merging into your Codex config.",
    "",
    `[mcp_servers.${config.serverName}]`,
    `command = ${tomlString(config.command)}`,
    "args = [",
    ...config.args.map((arg) => `  ${tomlString(arg)}`),
    "]",
    "env = {}",
    ""
  ];
  return lines.join("\n");
}

function renderClaudeJson(config) {
  return {
    mcpServers: {
      [config.serverName]: {
        command: config.command,
        args: config.args,
        env: config.env
      }
    }
  };
}

function renderReadme(config) {
  return [
    "# Generated MCP Config",
    "",
    "These files are local installation helpers for `overleaf-browser-bridge`.",
    "",
    "- `codex-mcp.toml`: Codex MCP server snippet.",
    "- `mcp-launch.json`: Claude Desktop or Claude Code-style MCP server config.",
    "",
    "Review paths before copying them into a global agent config. Generated files can contain local absolute paths, so keep this directory private and do not commit it.",
    "",
    "Server entry:",
    "",
    "```text",
    `${config.command} ${config.args.join(" ")}`,
    "```",
    ""
  ].join("\n");
}

function tomlString(value) {
  return `"${String(value).replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
}

function parseArgs(argv) {
  const options = {};
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === "--help" || arg === "-h") {
      printHelp();
      process.exit(0);
    }
    if (arg === "--repo-path") {
      options.repoPath = takeValue(argv, ++index, arg);
    } else if (arg === "--out-dir") {
      options.outDir = takeValue(argv, ++index, arg);
    } else if (arg === "--mode") {
      options.mode = takeValue(argv, ++index, arg);
    } else {
      throw new Error(`Unknown argument: ${arg}`);
    }
  }
  return options;
}

function takeValue(argv, index, flag) {
  const value = argv[index];
  if (!value || value.startsWith("--")) throw new Error(`${flag} requires a value`);
  return value;
}

function printHelp() {
  console.log(`Usage: node scripts/generate-mcp-config.js [options]

Options:
  --repo-path <path>   Repository path for source mode. Defaults to this repository.
  --out-dir <path>     Output directory. Defaults to .runtime/generated-configs.
  --mode <mode>        source or package. Defaults to source.
  -h, --help           Show this help.

The generated files may contain local absolute paths. Keep them private and do not commit them.`);
}

if (require.main === module) {
  main();
}

module.exports = {
  buildMcpConfig,
  renderCodexToml,
  renderClaudeJson,
  tomlString
};
